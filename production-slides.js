  var reduceMotion = window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches;

  cards.forEach(function (card) {
    var img = card.querySelector('.cat-media img') || card.querySelector('img');
    if (!img) return;

    img.removeAttribute('srcset');

    var deck = [];
    var at = 0;
    var current = img.getAttribute('src') || '';
    var onScreen = true;

    function shuffleDeck() {
      deck = PATHS.slice();
      for (var i = deck.length - 1; i > 0; i--) {
        var j = Math.floor(Math.random() * (i + 1));
        var t = deck[i]; deck[i] = deck[j]; deck[j] = t;
      }
      /* Never reuse the image that is currently visible as the first of a new deck. */
      if (deck.length > 1 && BASE + deck[0] === current) {
        var k = 1 + Math.floor(Math.random() * (deck.length - 1));
        var tmp = deck[0]; deck[0] = deck[k]; deck[k] = tmp;
      }
      at = 0;
    }

    function nextSrc() {
      if (at >= deck.length) shuffleDeck();
      var src = BASE + deck[at++];
      if (src === current && deck.length > 1) {
        if (at >= deck.length) shuffleDeck();
        src = BASE + deck[at++];
      }
      return src;
    }

    function paint(src) {
      img.src = src;
      current = src;
      if (!reduceMotion && img.animate) {
        img.animate(
          [{ opacity: 0.3 }, { opacity: 1 }],
          { duration: 450, easing: 'ease-out' }
        );
      }
    }

    function advance() {
      if (document.hidden || !onScreen) return;
      var src = nextSrc();
      var probe = new Image();
      probe.decoding = 'async';
      probe.onload = function () { paint(src); };
      probe.onerror = function () { /* skip unreachable image; next tick tries another */ };
      probe.src = src;
    }

    if ('IntersectionObserver' in window) {
      new IntersectionObserver(function (entries) {
        onScreen = entries[0].isIntersecting;
      }, { rootMargin: '200px' }).observe(card);
    }

    shuffleDeck();
    advance();
    setInterval(advance, INTERVAL);
  });
